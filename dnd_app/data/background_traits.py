"""Each background's suggested characteristics -- its personality traits,
ideals, bonds and flaws, the tables the books give to roll on or pick
from -- for the Notes page's suggestions (both apps).

Read from docs/reference/backgrounds-sublist.md and kept as data in
background_traits_data.py beside this file; run this file to rebuild it:

    python -m dnd_app.data.background_traits

A background whose book says to use another's tables ("use the tables for
the soldier background") gets that one's."""
import os
import re

_HERE = os.path.dirname(os.path.abspath(__file__))
_SRC = os.path.join(_HERE, "..", "..", "docs", "reference", "backgrounds-sublist.md")
_DATA = os.path.join(_HERE, "background_traits_data.py")

KINDS = ("traits", "ideals", "bonds", "flaws")
_HEADS = {"personality trait": "traits", "personality traits": "traits", "trait": "traits",
          "ideal": "ideals", "ideals": "ideals", "bond": "bonds", "bonds": "bonds",
          "flaw": "flaws", "flaws": "flaws"}
_TABLE = re.compile(r"^\|\s*d\d+\s*\|\s*([^|]+?)\s*\|[ \t]*\n\|[-:| ]+\|[ \t]*\n((?:\|[^\n]*\|[ \t]*\n?)+)", re.M)
_BORROW = re.compile(r"[Uu]se the tables for the ([a-z' -]+?) background", re.I)

# the app's names for backgrounds the reference names otherwise
ALIASES = {
    "Knight": "Variant Noble (Knight)",
    "Pirate": "Variant Sailor (Pirate)",
    "Sailor (Variant: Pirate)": "Variant Sailor (Pirate)",
    "Sage (Variant: Wizard's Apprentice)": "Sage",
}


def build() -> dict:
    """{background: {"traits": [...], "ideals": [...], "bonds": [...], "flaws": [...]}}"""
    text = open(_SRC, encoding="utf-8").read()
    out, borrows = {}, {}
    for sec in re.split(r"^## ", text, flags=re.M)[1:]:
        name = sec.split("\n", 1)[0].strip()
        found = {}
        for m in _TABLE.finditer(sec):
            kind = _HEADS.get(m.group(1).strip().lower())
            if not kind:
                continue
            for line in m.group(2).strip().split("\n"):
                cells = [c.strip() for c in line.strip().strip("|").split("|")]
                if len(cells) >= 2 and cells[1]:
                    found.setdefault(kind, []).append(cells[1])
        if found:
            out[name] = {k: found.get(k, []) for k in KINDS}
        else:
            b = _BORROW.search(sec)
            if b:
                borrows[name] = b.group(1).strip().title()
    for name, other in borrows.items():
        if other in out:
            out[name] = out[other]
    return out


def write(data: dict) -> None:
    lines = ['"""Generated by background_traits.py from docs/reference/backgrounds-sublist.md -- '
             'don\'t edit by hand."""', "", "TRAITS = {"]
    for name in sorted(data):
        lines.append(f"    {name!r}: {{")
        for k in KINDS:
            lines.append(f"        {k!r}: [")
            lines.extend(f"            {t!r}," for t in data[name][k])
            lines.append("        ],")
        lines.append("    },")
    lines.append("}")
    open(_DATA, "w", encoding="utf-8").write("\n".join(lines) + "\n")


def suggestions(background: str) -> dict:
    """The tables for a background ({} when its book has none)."""
    try:
        from dnd_app.data.background_traits_data import TRAITS
    except ImportError:
        return {}
    name = (background or "").strip()
    return TRAITS.get(name) or TRAITS.get(ALIASES.get(name, "")) or {}


if __name__ == "__main__":
    d = build()
    write(d)
    print(f"{len(d)} backgrounds written to {os.path.relpath(_DATA)}")

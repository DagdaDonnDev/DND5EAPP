"""
D&D 5e 2024 PHB Classes
Key 2024 changes:
- Weapon Mastery system added for martial classes
- Fighting Styles are now Fighting Style FEATS (swappable each level)
- All ASI/Feat moments give EITHER ASI or any feat (no longer just optional)
- Subclass levels shifted for several classes (Bard→3, Fighter→3, Ranger→3, etc.)
- Rogue: Cunning Strikes replaces old Cunning Action expansions
- Cleric: Channel Divinity refreshes on SR (1 use)
- Paladin: Divine Smite is now a spell, Channel Divinity (not per day)
- Warlock: Pact Magic slots now interoperate with Spellcasting fully
- Druid: Wild Shape grants temp HP = Druid level; no CR restrictions by default
- Ranger: Deft Explorer replaces Natural Explorer, Favored Foe replaces Favored Enemy
- Barbarian: Primal Knowledge at 3 and 10, Instinctive Pounce merged
- Sorcerer: Innate Sorcery at 1, Font of Magic at 2; Metamagic options +2 at 10 and 17
- Epic Boon feats at 19th level (replaces old ASI/Feat slot)

Author: Ethan O'Brien
Date: 2026-08-20
"""

